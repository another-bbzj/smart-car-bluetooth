/*********************************************************************************************************************
* 文件名称          Car_PID.h
* 功能说明          双轮车速度环：位置式 PID 与增量式 PID 的数据结构和接口声明。
*
*                   位置式 Car_Pid_*：默认控制路径，输出带硬限幅和条件积分抗饱和。
*                   增量式 Car_IncPid_*：位置式的"速度型"版本，接口风格一致，默认关闭，
*                   在 Car_Config.h 中把 CAR_PID_USE_INCREMENTAL 设为 1 后由 Car_Tick 启用。
*
*                   误差   e = 目标转速 - 实际转速
*                   比例   P = Kp × e                              误差越大，出力越大
*                   积分   I = I + Ki × e（每个控制周期累加一次）    消除稳态误差、抵抗负载
*                   微分   D = -Kd × (本次实际 - 上次实际)          抑制转速变化过快；用实测值变化量，
*                                                                   目标突变时不会产生微分冲击
*                   输出   = P + I + D，限制在 ±output_limit（PWM 计数）
*
*                   抗积分饱和：输出已经顶到限幅、误差还在往同一方向推时，积分最多只长到
*                   "输出刚好顶满"为止，不再继续累加；否则堵转或加速跟不上时积分会越积越大。
*
* 修改记录
* 日期              作者                备注
* 2026-09-27                            first version
* 2026-11-12                            统一格式与中文注释，限幅改用 Car_Utils
* 2026-11-12                            新增增量式 Car_IncPid_* 与编译开关
********************************************************************************************************************/
#ifndef CAR_PID_H
#define CAR_PID_H

#include <stdint.h>

/* 单个速度环 PID 的完整状态 */
typedef struct {
    float   kp;             /* 比例系数：误差的即时放大倍数 */
    float   ki;             /* 积分系数：每个控制周期累加误差的权重 */
    float   kd;             /* 微分系数：按实测转速变化量抑制超调 */
    float   output_limit;   /* 输出限幅绝对值（PWM 计数），本车为 CAR_PWM_LIMIT = 3500 */
    float   integral;       /* 积分项 I 的累计值（已做抗饱和处理） */
    float   last_measure;   /* 上一次实测转速，用于计算微分项 */
    uint8_t started;        /* 微分启动标志：0 表示还没有"上一次实测值"，本次跳过微分 */
} Car_Pid_Struct;

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_Pid_init
 * 功能说明    写入 Kp/Ki/Kd 与输出限幅，并清空积分和历史状态。
 * 用法        上电初始化或停车修改参数时调用；之后每个控制周期调用 Car_Pid_update。
 * 参数说明    pid          —— 待初始化的 PID 对象指针
 *             kp/ki/kd     —— 比例、积分、微分参数（按 5ms 离散周期整定）
 *             output_limit —— 输出限幅绝对值（PWM 计数）
 * 返回说明    无
 * 示例        Car_Pid_Struct pid;
 *             Car_Pid_init(&pid, 2.0f, 0.12f, 0.0f, 3500.0f);
 * 备注        内部调用 Car_Pid_reset，因此重复初始化等于"换参数并清状态"。
 *-------------------------------------------------------------------------------------------------------------------*/
void Car_Pid_init(Car_Pid_Struct *pid, float kp, float ki, float kd, float output_limit);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_Pid_reset
 * 功能说明    清空积分项、上一次实测值和微分启动标志，但保留 Kp/Ki/Kd 与输出限幅。
 * 用法        启动、停止、急停、故障复位、目标归零等需要"从零开始"的时机调用。
 * 参数说明    pid —— 待复位的 PID 对象指针
 * 返回说明    无
 * 示例        Car_Pid_reset(&car.pid[0]);
 * 备注        复位后第一次 update 不计算微分项，避免历史值缺失导致 D 项冲击。
 *-------------------------------------------------------------------------------------------------------------------*/
void Car_Pid_reset(Car_Pid_Struct *pid);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_Pid_update
 * 功能说明    执行一次位置式 PID 计算，输出已限幅在 ±output_limit 内。
 * 用法        每个控制周期（本项目 5ms）对每个轮子各调用一次；目标与实测单位必须一致（rpm）。
 * 参数说明    pid     —— PID 对象指针（需先 Car_Pid_init）
 *             target  —— 目标转速（rpm）
 *             measure —— 实测转速（rpm）
 * 返回说明    限幅后的控制量（PWM 计数），正负号表示期望的转动方向
 * 示例        float pwm = Car_Pid_update(&car.pid[0], 80.0f, car.speed[0]);
 * 备注        1) 微分项使用 -Kd × (本次实测 - 上次实测)，目标突变不会产生微分冲击；
 *             2) 输出顶到限幅且误差同向时，积分最多只增加到"输出刚好顶满"，避免积分饱和；
 *             3) 目标与实测均为 0 时建议由调用方直接输出 0 并复位。
 *-------------------------------------------------------------------------------------------------------------------*/
float Car_Pid_update(Car_Pid_Struct *pid, float target, float measure);

/* ============================ 增量式 PID（位置式的"速度型"版本） ============================ */
/* 本组把位置式输出逐拍作差，得到 ΔPWM 后再累加，接口风格与 Car_Pid_* 一致。
 * 未饱和时，递推结果与 Car_Pid_update 的位置式结果逐拍一致；饱和时冻结积分增量，
 * 并始终把累加输出限制在 ±output_limit。第一拍输出与位置式首次输出一致（P+I，D=0）。
 * 在 Car_Config.h 中把 CAR_PID_USE_INCREMENTAL 设为 1，即可在 Car_Tick 中启用本组；
 * 默认 0，保持原有位置式控制行为。 */
typedef struct {
    float   kp;             /* 比例系数 */
    float   ki;             /* 积分系数（每个控制周期累加一次） */
    float   kd;             /* 微分系数，按实测转速变化量抑制超调 */
    float   output_limit;   /* 绝对输出限幅（PWM 计数） */
    float   output;         /* 当前累加输出，也是增量式的"积分状态" */
    float   error_prev;     /* 上一次误差 e[k-1] */
    float   measure_prev;   /* 上一次实测值 y[k-1] */
    float   measure_prev2;  /* 上上次实测值 y[k-2] */
    uint8_t started;        /* 0 表示尚未建立历史，第一拍走初始化分支 */
} Car_IncPid_Struct;

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_IncPid_init
 * 功能说明    写入增量式 PID 的 Kp/Ki/Kd 与绝对输出限幅，并清空累加输出和历史状态。
 * 用法        上电初始化或停车修改参数时调用；之后每个控制周期调用 Car_IncPid_update。
 * 参数说明    pid          —— 待初始化的增量式 PID 对象指针
 *             kp/ki/kd     —— 比例、积分、微分参数（按 5ms 离散周期整定）
 *             output_limit —— 绝对输出限幅（PWM 计数）
 * 返回说明    无
 * 示例        Car_IncPid_Struct inc_pid;
 *             Car_IncPid_init(&inc_pid, 2.0f, 0.12f, 0.0f, 3500.0f);
 * 备注        内部调用 Car_IncPid_reset，重复初始化等于"换参数并清状态"。
 *-------------------------------------------------------------------------------------------------------------------*/
void Car_IncPid_init(Car_IncPid_Struct *pid, float kp, float ki, float kd, float output_limit);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_IncPid_reset
 * 功能说明    清空累加输出、误差历史、实测历史和启动标志，但保留 Kp/Ki/Kd 与输出限幅。
 * 用法        启动、停止、急停、故障复位、目标归零等需要"从零开始"的时机调用。
 * 参数说明    pid —— 待复位的增量式 PID 对象指针
 * 返回说明    无
 * 示例        Car_IncPid_reset(&inc_pid);
 * 备注        复位后第一拍重新走"P+I、D=0"的初始化分支。
 *-------------------------------------------------------------------------------------------------------------------*/
void Car_IncPid_reset(Car_IncPid_Struct *pid);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_IncPid_update
 * 功能说明    执行一拍增量式 PID：ΔPWM = Kp·Δe + Ki·e - Kd·Δ²y，累加后限幅在 ±output_limit。
 * 用法        每个控制周期对每个轮子各调用一次；返回绝对 PWM 计数，可直接交给 CarMotor_SetOutput。
 * 参数说明    pid     —— 增量式 PID 对象指针（需先 Car_IncPid_init）
 *             target  —— 目标转速（rpm）
 *             measure —— 实测转速（rpm）
 * 返回说明    限幅后的绝对控制量（PWM 计数），正负号表示期望方向
 * 示例        float pwm = Car_IncPid_update(&inc_pid, 80.0f, speed);
 * 备注        1) 微分使用实测值的二阶差分，目标阶跃不产生 D 冲击；
 *             2) 输出已经顶到限幅且误差还在同方向推时，本拍冻结积分增量，防止饱和累积；
 *             3) 未饱和时与 Car_Pid_update 的位置式结果逐拍一致，便于台架对比。
 *-------------------------------------------------------------------------------------------------------------------*/
float Car_IncPid_update(Car_IncPid_Struct *pid, float target, float measure);

#endif /* CAR_PID_H */
