#ifndef CAR_MOTOR_H
#define CAR_MOTOR_H

/*********************************************************************************************************************
* 文件名称          Car_Motor.h
* 功能说明          双路直流电机驱动接口：方向 GPIO + PWM 占空比。
*
*                   一个电机由两个引脚控制：
*                   · 方向脚（CAR_LEFT_DIR / CAR_RIGHT_DIR）：决定正转或反转
*                   · PWM 脚（CAR_LEFT_PWM / CAR_RIGHT_PWM）：决定输出占空比
*
*                   本模块只负责"把带符号的 PWM 请求写到硬件"，不参与 PID、状态机和保护判断。
*                   换向时先输出一个控制周期的零占空比，避免 H 桥在正反转之间直接切换造成电流冲击。
*
* 修改记录
* 日期              作者                备注
* 2026-11-12                            从 Car_Hardware.c 拆出电机外设模块
*********************************************************************************************************************/
#include <stdint.h>

#define CAR_MOTOR_LEFT   0U     /* 左轮下标 */
#define CAR_MOTOR_RIGHT  1U     /* 右轮下标 */

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    CarMotor_Init
 * 功能说明    初始化左右轮方向脚为推挽输出（先输出正转电平），并把 PWM 占空比初始化为 0。
 * 用法        上电初始化阶段调用一次，必须早于 CarMotor_SetOutput。
 * 参数说明    无
 * 返回说明    无
 * 示例        CarMotor_Init();
 * 备注        方向脚初始电平由 CAR_LEFT_FORWARD_HIGH / CAR_RIGHT_FORWARD_HIGH 决定；
 *             PWM 频率由 CAR_PWM_HZ 决定。
 *-------------------------------------------------------------------------------------------------------------------*/
void CarMotor_Init(void);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    CarMotor_SetOutput
 * 功能说明    把一路带符号的 PWM 请求写到硬件：处理方向脚与占空比，换向时先插入一拍零输出。
 * 用法        由 5ms 控制拍在 Car_Tick 之后对左右轮各调用一次。
 * 参数说明    index —— 轮子下标：CAR_MOTOR_LEFT(0) 或 CAR_MOTOR_RIGHT(1)
 *             value —— 速度环输出（PWM 计数），正负表示方向，0 表示停止
 * 返回说明    无
 * 示例        CarMotor_SetOutput(CAR_MOTOR_LEFT, car.output[0]);
 *             CarMotor_SetOutput(CAR_MOTOR_RIGHT, car.output[1]);
 * 备注        1) value == 0 时立即写 0 并清除换向等待标志；
 *             2) 方向需要改变时，先写 0 并置等待标志，下一拍再真正换向并输出，
 *                因此换向瞬间实际输出会晚一个控制周期；
 *             3) 方向极性由 CAR_LEFT_FORWARD_HIGH / CAR_RIGHT_FORWARD_HIGH 决定；
 *             4) index 越界时直接返回，避免访问数组越界。
 *-------------------------------------------------------------------------------------------------------------------*/
void CarMotor_SetOutput(uint8_t index, float value);

#endif /* CAR_MOTOR_H */
