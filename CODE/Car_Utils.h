#ifndef CAR_UTILS_H
#define CAR_UTILS_H

/*********************************************************************************************************************
* 文件名称          Car_Utils.h
* 功能说明          整车通用工具函数：浮点绝对值、对称限幅、大端字节序读取。
*
*                   这些函数原先在 Car_Core.c、Car_Vision.c、Car_PID.c 中各自实现了一份，
*                   语义相同但名字不同（absolute/clamp/limit_abs/u16/u32/i16/signed_rpm）。
*                   现统一收敛到本模块，避免同一逻辑多份副本在后续修改中走样。
*
*                   本模块不依赖任何外设，只依赖 <stdint.h>，可被控制层、协议层和驱动层共同使用。
*
* 修改记录
* 日期              作者                备注
* 2026-11-12                            从 Car_Core/Car_Vision/Car_PID 抽取公共工具
********************************************************************************************************************/
#include <stdint.h>

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_AbsFloat
 * 功能说明    求浮点数的绝对值，不依赖 math.h，适合在中断中调用。
 * 参数说明    x —— 任意浮点数
 * 返回说明    |x|；NaN 输入时返回 NaN（与逐位比较实现一致）
 * 备注        原 Car_Core.c 的 static float absolute()。
 *-------------------------------------------------------------------------------------------------------------------*/
float Car_AbsFloat(float x);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_ClampFloat
 * 功能说明    把浮点数限制在 [-limit, +limit] 区间内，超出时取边界值。
 * 参数说明    x     —— 待限幅的数值
 *             limit —— 限幅绝对值，必须为非负数
 * 返回说明    限幅后的数值；NaN 输入时返回 NaN
 * 备注        原 Car_Core.c 的 clamp() 与 Car_PID.c 的 limit_abs() 合并而来。
 *-------------------------------------------------------------------------------------------------------------------*/
float Car_ClampFloat(float x, float limit);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_ReadU16BE
 * 功能说明    从大端字节序的 2 个字节还原 16 位无符号整数。
 * 参数说明    p —— 指向至少 2 字节数据的指针
 * 返回说明    解析出的 uint16_t
 * 备注        原 Car_Core.c 的 u16() 与 Car_Vision.c 的 u16()；不检查指针边界。
 *-------------------------------------------------------------------------------------------------------------------*/
uint16_t Car_ReadU16BE(const uint8_t *p);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_ReadU32BE
 * 功能说明    从大端字节序的 4 个字节还原 32 位无符号整数。
 * 参数说明    p —— 指向至少 4 字节数据的指针
 * 返回说明    解析出的 uint32_t
 * 备注        原 Car_Vision.c 的 u32()，由两次 Car_ReadU16BE 拼接实现。
 *-------------------------------------------------------------------------------------------------------------------*/
uint32_t Car_ReadU32BE(const uint8_t *p);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_ReadI16BE
 * 功能说明    从大端字节序的 2 个字节还原 16 位有符号整数（补码）。
 * 参数说明    p —— 指向至少 2 字节大端补码数据的指针
 * 返回说明    -32768 ~ 32767 的 int32_t
 * 备注        原 Car_Core.c 的 signed_rpm() 与 Car_Vision.c 的 i16() 合并而来。
 *-------------------------------------------------------------------------------------------------------------------*/
int32_t Car_ReadI16BE(const uint8_t *p);

#endif /* CAR_UTILS_H */
