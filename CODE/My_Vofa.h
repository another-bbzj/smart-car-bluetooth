/*********************************************************************************************************************
* 文件名称          My_Vofa.h
* 功能说明          向上位机 VOFA+ 发送波形数据（JustFloat 协议）的接口声明。
*
*                   JustFloat 帧格式：N 个 float（每个 4 字节，小端）+ 帧尾 00 00 80 7F。
*                   VOFA+ 收到后把第 1 个 float 画成通道 I0，第 2 个画成 I1，依此类推。
*
*                   为什么分成 push 和 poll 两个函数：
*                   9600 波特率下发一个字节约 1.04ms，一帧 68 字节约 70ms。
*                   如果在定时中断里直接发送，中断会被严重拖长。因此：
*                   · 定时中断里调用 My_Vofa_push()：只把一帧数据放进软件 FIFO，几微秒返回；
*                   · 主循环里调用 My_Vofa_poll()：慢慢把 FIFO 里的字节发到串口。
*                   缓冲放不下时整帧丢弃，不会出现"半帧"，VOFA+ 不会解析错位。
*
* 修改记录
* 日期              作者                备注
* 2026-09-27                            first version
* 2026-11-12                            统一格式与中文注释
********************************************************************************************************************/
#ifndef MY_VOFA_H
#define MY_VOFA_H

#include <stdint.h>

#define MY_VOFA_MAX_CHANNELS  16U      /* 一帧最多 16 个通道，对应 16 个 float */
#define MY_VOFA_FIFO_SIZE     2048U    /* 发送缓冲大小（字节），主循环忙时先存在这里 */

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    My_Vofa_init
 * 功能说明    绑定输出串口，并初始化基于 NEUQ_FIFO 的软件发送缓冲。
 * 用法        在目标串口已经完成 NEUQ_Uart_init 之后调用一次。
 * 参数说明    uart_dev —— 发送所用串口编号（UART_0 ~ UART_3），本车为 UART_3（UART4）
 * 返回说明    无
 * 示例        NEUQ_Uart_init((UART_DEV_ENUM)CAR_UART_INDEX, CAR_UART_BAUD);
 *             My_Vofa_init(CAR_UART_INDEX);
 * 备注        发送与接收共用同一个蓝牙串口：上行是 VOFA+ 遥测，下行是 C3 3C 命令帧。
 *-------------------------------------------------------------------------------------------------------------------*/
void My_Vofa_init(uint8_t uart_dev);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    My_Vofa_push
 * 功能说明    把一帧 JustFloat 数据（N 个小端 float + 帧尾）整体放入发送缓冲；
 *             缓冲剩余空间不足时整帧丢弃，保证上位机不会收到半帧而错位。
 * 用法        在定时中断等实时上下文中调用（本项目每 100ms 一次），只做内存拷贝，不阻塞等待串口。
 * 参数说明    data     —— 通道数据数组，每个 float 对应 VOFA+ 的一个通道
 *             channels —— 通道数，范围 1 ~ MY_VOFA_MAX_CHANNELS
 * 返回说明    1 表示整帧成功入队；0 表示通道数非法或缓冲空间不足，整帧已丢弃
 * 示例        float ch[16] = { ... };
 *             My_Vofa_push(ch, 16);
 * 备注        STM32 与 PC 均为小端，float 直接按内存拷贝即为 JustFloat 要求的字节序；
 *             本函数不发送数据，真正发送由主循环的 My_Vofa_poll 完成。
 *-------------------------------------------------------------------------------------------------------------------*/
uint8_t My_Vofa_push(const float *data, uint8_t channels);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    My_Vofa_poll
 * 功能说明    把发送缓冲中"调用这一刻"已有的字节逐个写入串口，发送完即返回。
 * 用法        在主循环中反复调用（本项目 Car_Main 的 while(1) 只调用它）。
 * 参数说明    无
 * 返回说明    无
 * 示例        while (1) { My_Vofa_poll(); }
 * 备注        1) 只发送进入函数时缓冲中的字节数，中断期间新入队的数据留到下一次；
 *             2) NEUQ_Uart_write_byte 会等待发送数据寄存器空（TXE），9600 下约 1ms/字节；
 *             3) 缓冲满时 push 整帧丢弃，因此主循环应及时轮询，避免遥测丢失。
 *-------------------------------------------------------------------------------------------------------------------*/
void My_Vofa_poll(void);

#endif /* MY_VOFA_H */
