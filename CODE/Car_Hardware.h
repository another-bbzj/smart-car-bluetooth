#ifndef CAR_HARDWARE_H
#define CAR_HARDWARE_H

/*********************************************************************************************************************
* 文件名称          Car_Hardware.h
* 功能说明          整车应用的板级入口：初始化各外设模块并驱动 5ms 控制拍。
*
*                   对外接口只有两个：
*                   · Car_Main        —— 上电初始化并进入主循环
*                   · Car_PIT_Handler —— 5ms 定时中断主流程
*
*                   蓝牙/视觉接收回调与视觉快照接口的声明在 Car_Link.h 中，
*                   本头文件已包含它，因此旧代码仍可只包含 Car_Hardware.h。
*
* 修改记录
* 日期              作者                备注
* 2026-09-27                            first version
* 2026-11-12                            拆分电机/编码器/链路模块，本文件只保留板级编排
*********************************************************************************************************************/
#include <stdint.h>
#include "Car_Link.h"

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_Main
 * 功能说明    整车初始化并进入主循环：初始化控制核心、通信链路、Flash 片选、电机、编码器、
 *             两路串口及中断、5ms 定时器，然后循环执行 VOFA+ 数据发送。
 * 用法        由 User_Main 调用一次，之后不再返回；必须先确认接线和配置再上电。
 * 参数说明    无
 * 返回说明    无（正常情况下不返回）
 * 示例        void User_Main(void) { Car_Main(); }
 * 备注        1) Flash 片选 CAR_FLASH_CS 初始化为高，避免与 PA5/6/7 复用冲突；
 *             2) 上电后处于 STOP，必须收到合法 ARM 且再收到轮速命令才会运动；
 *             3) 蓝牙 UART4 中断优先级 3，视觉 USART3 优先级 4；
 *             4) 主循环只做 My_Vofa_poll，实际控制全部在 5ms 中断中完成。
 *-------------------------------------------------------------------------------------------------------------------*/
void Car_Main(void);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    Car_PIT_Handler
 * 功能说明    5ms 定时中断主流程：读取编码器增量、处理串口故障与命令解析、执行速度控制与电机输出，
 *             批量处理视觉数据，并按 100ms 周期通过 VOFA+ JustFloat 回传 16 通道遥测。
 * 用法        由库的 TIM6 定时中断回调 NEUQ_PIT_1_CALLBACK 调用，必须严格保持 5ms 周期。
 * 参数说明    无
 * 返回说明    无
 * 示例        void NEUQ_PIT_1_CALLBACK(void) { Car_PIT_Handler(); }
 * 备注        1) 执行顺序固定为"采样 -> 保护/解析 -> 控制 -> 输出 -> 视觉 -> 遥测"，
 *                保证电机输出始终基于本拍最新数据；
 *             2) 视觉处理放在电机输出之后，且每拍最多处理 64 字节，避免拖长控制中断；
 *             3) 遥测 20 拍（100ms）发一帧，9600 波特率下占用约 680 字节/秒。
 *-------------------------------------------------------------------------------------------------------------------*/
void Car_PIT_Handler(void);

#endif /* CAR_HARDWARE_H */
