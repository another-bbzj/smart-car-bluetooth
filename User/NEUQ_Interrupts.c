/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    NEUQ_PIT_1_CALLBACK
 * 功能说明    定时器 1（本项目为 TIM6，5ms）中断回调入口，把控制权交给整车 5ms 控制拍 Car_PIT_Handler。
 * 用法        由 NEUQ 库的 PIT 中断服务函数周期调用，用户不要手动调用。
 * 参数说明    无
 * 返回说明    无
 * 示例        // Car_Main 中 NEUQ_PIT_init_ms(PIT_CH1, CAR_PERIOD_MS) 之后，
 *             // 每 5ms 自动进入本函数执行采样、控制、保护和回传
 * 备注        回调节奏由 CAR_PERIOD_MS 决定；修改控制周期后 PID 参数与保护阈值需重新整定。
 *-------------------------------------------------------------------------------------------------------------------*/
void NEUQ_PIT_1_CALLBACK(void)
{
    Car_PIT_Handler();                                      /* 整车控制全部在 5ms 拍内完成 */
}

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    NEUQ_PIT_2_CALLBACK
 * 功能说明    定时器 2 中断回调占位，本项目未使用，保持为空。
 * 用法        若后续需要第二路周期任务，可在 Car_Main 中初始化 PIT_CH2 并在此实现。
 * 参数说明    无
 * 返回说明    无
 * 示例        保留占位：例如在此加入 1ms 的按键扫描或状态机节拍。
 * 备注        本项目所有实时控制都集中在 5ms 的 PIT_1 中，避免多节拍竞争共享状态。
 *-------------------------------------------------------------------------------------------------------------------*/
void NEUQ_PIT_2_CALLBACK(void)
{
    /* 本项目未使用 TIM7 周期任务 */
}

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    TS_UART_0_RX_CALLBACK
 * 功能说明    串口 0 接收回调：仅当 CAR_UART_INDEX == 0 时把字节转交蓝牙命令接收处理，否则丢弃。
 * 用法        由 NEUQ 库的 UART0 接收中断自动调用；本车蓝牙实际使用 UART_3（UART4），因此默认分支为空。
 * 参数说明    dat —— 收到的单字节
 * 返回说明    无
 * 示例        // 若把蓝牙改到 UART_0，只需在 Car_Config.h 中令 CAR_UART_INDEX 为 0
 * 备注        接收回调只入队，不在中断内解析协议。
 *-------------------------------------------------------------------------------------------------------------------*/
void TS_UART_0_RX_CALLBACK(uint8_t dat)
{
#if CAR_UART_INDEX == 0
    Car_UART_RX_Handler(dat);                               /* 蓝牙映射到 UART_0 时才入队 */
#else
    (void)dat;                                              /* 未使用该路，显式丢弃并消除未使用告警 */
#endif
}

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    TS_UART_1_RX_CALLBACK
 * 功能说明    串口 1 接收回调：仅当 CAR_UART_INDEX == 1 时转交蓝牙命令接收处理，否则丢弃。
 * 用法        由 NEUQ 库的 UART1 接收中断自动调用；当前配置下不参与业务。
 * 参数说明    dat —— 收到的单字节
 * 返回说明    无
 * 示例        // 若要改接 UART_1，修改 Car_Config.h 的 CAR_UART_INDEX 后重新编译
 * 备注        本项目板级适配只允许蓝牙 UART4 与视觉 USART3，改索引会被 #error 拦截。
 *-------------------------------------------------------------------------------------------------------------------*/
void TS_UART_1_RX_CALLBACK(uint8_t dat)
{
#if CAR_UART_INDEX == 1
    Car_UART_RX_Handler(dat);                               /* 蓝牙映射到 UART_1 时才入队 */
#else
    (void)dat;                                              /* 未使用该路，显式丢弃 */
#endif
}

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    TS_UART_2_RX_CALLBACK
 * 功能说明    串口 2（USART3）接收回调：把香橙派视觉数据字节转交独立视觉接收缓冲。
 * 用法        由 NEUQ 库的 USART3 接收中断自动调用，固定映射视觉链路，与蓝牙无关。
 * 参数说明    dat —— 收到的单字节
 * 返回说明    无
 * 示例        // 香橙派每发 1 字节视觉帧，就进入本函数写入 vision_fifo；
 *             // 5ms 控制拍再批量解析，不会阻塞中断
 * 备注        视觉数据不能启动电机或写 PWM，只提供观测与数独子块。
 *-------------------------------------------------------------------------------------------------------------------*/
void TS_UART_2_RX_CALLBACK(uint8_t dat)
{
    Car_Vision_UART_RX_Handler(dat);                        /* 视觉字节只入队，解析放在控制拍 */
}

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    TS_UART_3_RX_CALLBACK
 * 功能说明    串口 3（UART4）接收回调：当 CAR_UART_INDEX == 3 时转交蓝牙命令接收处理，否则丢弃。
 * 用法        由 NEUQ 库的 UART4 接收中断自动调用；本车默认即使用该路接收 JDY-31 蓝牙数据。
 * 参数说明    dat —— 收到的单字节
 * 返回说明    无
 * 示例        // 手机/电脑经 JDY-31 发来的 C3 3C 命令帧，逐字节进入本回调
 * 备注        库中"UART_3"对应 STM32 的 UART4（PC10/PC11），与原理图命名不同，接线时勿混淆。
 *-------------------------------------------------------------------------------------------------------------------*/
void TS_UART_3_RX_CALLBACK(uint8_t dat)
{
#if CAR_UART_INDEX == 3
    Car_UART_RX_Handler(dat);                               /* 蓝牙默认走 UART4 */
#else
    (void)dat;                                              /* 未使用该路，显式丢弃 */
#endif
}

