/*
 * ============================================================================
 * 文件名称：NEUQ_Main.c
 * ============================================================================
 * 模块功能
 * ----------------------------------------------------------------------------
 * 本文件是蓝牙差速小车的应用入口。它只做一件事：调用 Car_Main()，
 * 把执行权交给底盘控制模块。
 *
 * 调用关系：
 *     User_Main()
 *         -> Car_Main()（Car_Hardware.c）
 *              -> 初始化控制对象、PWM、编码器、串口和 PIT
 *              -> 启动周期中断
 *              -> 主循环发送 VOFA+ 遥测，正常不会返回。
 *
 * 函数列表
 * ----------------------------------------------------------------------------
 *   void User_Main(void)
 *       —— 应用入口，启动蓝牙差速车后进入永久循环。
 *
 * 备注信息
 * ----------------------------------------------------------------------------
 *   Car_Main() 内部已有自己的 while(1) 遥测循环；这里的 while(1) 只是
 *   防御性写法，保证 Car_Main() 即使因异常返回，程序也不会跑飞。
 * ============================================================================
 */

#include "Car_Hardware.h"

/*
 * 函数名称：User_Main
 * 函数功能：蓝牙差速车应用入口，初始化硬件并启动双轮闭环控制。
 * 参数说明：无。
 * 返回参数：无，正常不会返回。
 * 使用示例：
 *     // NEUQ 库启动文件在 main() 中调用 User_Main()
 *     int main(void)
 *     {
 *         User_Main();
 *     }
 * 备注信息：初始化硬件后，由 PIT 周期中断控制双轮，主循环发送遥测。
 */
void User_Main(void)
{
    Car_Main();    /* 初始化硬件并进入遥测主循环 */

    while (1)
    {
        /* Car_Main() 正常不会返回；保留空循环防止程序意外跑飞。 */
    }
}
