#include "Car_Hardware.h"

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称    User_Main
 * 功能说明    用户程序入口：启动蓝牙差速小车应用 Car_Main，之后进入空主循环（实际工作都在 5ms 中断中）。
 * 用法        由 HAL 的 main() 在完成 HAL_Init、时钟和外设初始化后调用一次，正常情况下不返回。
 * 参数说明    无
 * 返回说明    无（若返回，外层 while(1) 会保持空转）
 * 示例        // main.c 中：
 *             // MX_GPIO_Init(); ... User_Main();
 * 备注        本项目只保留双电机 + 前万向轮蓝牙调试程序；不要在此处再加入旧任务分支。
 *-------------------------------------------------------------------------------------------------------------------*/
void User_Main(void)
{
    Car_Main();                                             /* 整车初始化并进入内部主循环 */
    while (1) {
        /* Car_Main 正常不会返回；这里兜底保持空转，避免异常返回后跑飞 */
    }
}
